"""Word timings from parakeet JSON -> assets/vo/words/<beat>.json, beat starts -> assets/vo/starts.json,
and assets/js/vo.js. Run inside a chapter project. Gaps between beats come from GAPS (default 0.55 s);
the first beat starts at FIRST. Usage: make_vo_js.py [first=1.2] [beat:gap ...]"""
import json, sys, re, os

beats = [b['id'] for b in json.load(open('assets/vo/beats.json'))]
dur = json.load(open('assets/vo/durations.json'))
first = float(sys.argv[1]) if len(sys.argv) > 1 else 1.2
gaps = {a.split(':')[0]: float(a.split(':')[1]) for a in sys.argv[2:]}
os.makedirs('assets/vo/words', exist_ok=True)
for b in beats:
    h = json.load(open(f'assets/vo/tr/{b}.json'))
    words = []
    for s in h['sentences']:
        for t in s['tokens']:
            if t['text'].startswith(' ') or not words:
                words.append([t['text'].strip(), round(t['start'], 2), round(t['end'], 2)])
            else:
                words[-1][0] += t['text']
                words[-1][2] = round(t['end'], 2)
    json.dump(words, open(f'assets/vo/words/{b}.json', 'w'))
starts, t = {}, first
for b in beats:
    t += gaps.get(b, 0)
    starts[b] = round(t, 2)
    t = starts[b] + dur[b] + 0.55
json.dump(starts, open('assets/vo/starts.json', 'w'), indent=1)
out = {}
for b in beats:
    s = starts[b]
    w = json.load(open(f'assets/vo/words/{b}.json'))
    out[b] = {'start': s, 'dur': dur[b], 'words': [[x, round(s + a, 2), round(s + c, 2)] for x, a, c in w]}
open('assets/js/vo.js', 'w').write(
    '// Narration timing (generated by duo/tools/make_vo_js.py): absolute start, duration and word times in seconds.\n'
    'export const VO = ' + json.dumps(out) + ';\n\n'
    '''// absolute time of the n-th occurrence of a word (case-insensitive, punctuation ignored) in a beat
export function at(beat, word, n = 1) {
  const clean = (s) => s.toLowerCase().replace(/[^a-z0-9]/g, '');
  let k = 0;
  for (const [w, s] of VO[beat].words) if (clean(w) === clean(word) && ++k === n) return s;
  throw new Error(`word ${word} #${n} not in ${beat}`);
}
export const end = (beat) => VO[beat].start + VO[beat].dur;
export const start = (beat) => VO[beat].start;
export const LAST = ''' + str(round(t - 0.55, 2)) + ''';
''')
print('vo.js written; narration ends at', round(t - 0.55, 2))
